const dicts: Record<string, Dict> = {en, fr}

export type MessageKey = keyof Dict

export const locale = computed(() => prefs.language === 'auto'
	? (navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en')
	: prefs.language)

/** BCP-47 tag used for Intl date formatting. */
export const intlLocale = computed(() => locale.value === 'fr' ? 'fr-FR' : (navigator.language.startsWith('en') ? navigator.language : 'en-GB'))

export function t(key: MessageKey, params?: Record<string, string | number>): string {
	let msg = (dicts[locale.value] ?? en)[key] ?? en[key] ?? key
	if (params) {
		for (const [k, v] of Object.entries(params)) {
			msg = msg.replace(`{${k}}`, String(v))
		}
	}
	return msg
}
