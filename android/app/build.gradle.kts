// Release signing comes from keystore.properties (not committed; CI writes it
// from secrets). Without it, release builds are signed with the debug key so
// they still install, but can't update an app signed with the release key.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "org.opentick.android"
    compileSdk = 35

    defaultConfig {
        applicationId = "org.opentick.android"
        minSdk = 26
        targetSdk = 35
        // CI passes -PversionCode / -PversionName so every release can update the last one.
        versionCode = (findProperty("versionCode") as String?)?.toInt() ?: 1
        versionName = (findProperty("versionName") as String?) ?: "0.1.0"
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
        debug {
            applicationIdSuffix = ".debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = false
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
        unitTests.all { test ->
            // The sync test talks to a running server; see SyncTest.
            System.getenv("OPENTICK_TEST_SERVER")?.let { test.environment("OPENTICK_TEST_SERVER", it) }
        }
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

